import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DATA_BASE_URL = 'https://davidmegginson.github.io/ourairports-data';
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(projectRoot, 'src/data/airports.js');

const useOfflinePackages = process.argv.includes('--offline-packages');
const [airportRows, countryRows] = useOfflinePackages
  ? await loadOfflinePackageData()
  : await Promise.all([
      fetchCsv(`${DATA_BASE_URL}/airports.csv`),
      fetchCsv(`${DATA_BASE_URL}/countries.csv`),
    ]);

const countries = new Map(countryRows.map((country) => [country.code, country.name]));
const typeRank = new Map([
  ['large_airport', 0],
  ['medium_airport', 1],
  ['small_airport', 2],
  ['seaplane_base', 3],
  ['heliport', 4],
]);

const airports = airportRows
  .filter((airport) => airport.scheduled_service === 'yes' && /^[A-Z0-9]{3}$/.test(airport.iata_code))
  .map((airport) => ({
    id: `oa:${airport.id}`,
    iata: airport.iata_code,
    icao: airport.icao_code || airport.ident,
    name: airport.name,
    city: getPreferredCity(airport.iata_code, airport.municipality || airport.name),
    country: countries.get(airport.iso_country) || airport.iso_country,
    countryCode: airport.iso_country,
    latitude: toCoordinate(airport.latitude_deg),
    longitude: toCoordinate(airport.longitude_deg),
    aliases: splitKeywords(airport.keywords),
    type: airport.type,
  }))
  .sort((left, right) => {
    const typeDifference = (typeRank.get(left.type) ?? 9) - (typeRank.get(right.type) ?? 9);

    return typeDifference || left.city.localeCompare(right.city, 'en') || left.iata.localeCompare(right.iata, 'en');
  });

const source = `// Generated by npm run airports:update from OurAirports public-domain data.\n// Do not edit this file by hand.\nexport const airports = ${JSON.stringify(airports, null, 2)};\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, 'utf8');

console.log(`Wrote ${airports.length} scheduled passenger airports to ${outputPath}`);

async function loadOfflinePackageData() {
  const require = createRequire(import.meta.url);
  const currentAirportData = require('airport-data-js');
  const legacyData = require('airports-json');
  const currentAirports = await currentAirportData.findAirports({ scheduled_service: 'TRUE' });
  const legacyByIata = new Map(
    legacyData.airports.filter((airport) => airport.iata_code).map((airport) => [airport.iata_code, airport]),
  );

  return [
    currentAirports.map((airport) => {
      const legacyAirport = legacyByIata.get(airport.iata);

      return {
        id: legacyAirport?.id || `icao-${airport.icao || airport.iata}`,
        type: airport.type,
        name: airport.airport,
        latitude_deg: airport.latitude,
        longitude_deg: airport.longitude,
        iso_country: airport.country_code,
        municipality: legacyAirport?.municipality || deriveMunicipality(airport.airport),
        scheduled_service: 'yes',
        ident: airport.icao || airport.iata,
        icao_code: airport.icao,
        iata_code: airport.iata,
        keywords: legacyAirport?.keywords || '',
      };
    }),
    legacyData.countries,
  ];
}

async function fetchCsv(url) {
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`Could not download ${url}: ${response.status} ${response.statusText}`);
  }

  return parseCsv(await response.text());
}

function parseCsv(text) {
  const records = [];
  let record = [];
  let field = '';
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];

    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        field += character;
      }

      continue;
    }

    if (character === '"') {
      quoted = true;
    } else if (character === ',') {
      record.push(field);
      field = '';
    } else if (character === '\n') {
      record.push(field.replace(/\r$/, ''));
      records.push(record);
      record = [];
      field = '';
    } else {
      field += character;
    }
  }

  if (field || record.length) {
    record.push(field.replace(/\r$/, ''));
    records.push(record);
  }

  const [headers = [], ...rows] = records;

  return rows
    .filter((row) => row.some(Boolean))
    .map((row) => Object.fromEntries(headers.map((header, index) => [header, row[index] ?? ''])));
}

function splitKeywords(value) {
  return String(value ?? '')
    .split(',')
    .map((keyword) => keyword.trim())
    .filter(Boolean);
}

function toCoordinate(value) {
  const coordinate = Number(value);

  return Number.isFinite(coordinate) ? coordinate : null;
}

function deriveMunicipality(airportName) {
  return String(airportName ?? '')
    .replace(/\s+(international\s+)?(airport|airfield|aerodrome|heliport)$/i, '')
    .trim();
}

function getPreferredCity(iata, city) {
  const overrides = {
    IST: 'Istanbul',
    LED: 'Saint Petersburg',
  };

  return overrides[iata] ?? city;
}
